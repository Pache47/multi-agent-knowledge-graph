"""Check that a cleaner presentation preserves evidence, counts and conversation boundaries."""

import json
from pathlib import Path

import pytest
from conftest import answer
from streamlit.testing.v1 import AppTest

from factory_assistant.answer_models import EvidenceCard
from factory_assistant.answer_ui import cited_sources, conversation_context, event_summary
from factory_assistant.assistant import answer_question
from factory_assistant.assistant_contracts import SupportedClaim
from factory_assistant.scenarios import load_scenario

ROOT = Path(__file__).resolve().parents[1]


def test_all_record_count_is_broken_down_without_calling_every_record_a_stop():
    # The event card is generated by code; no language model chooses these numbers.
    card = EvidenceCard(
        id="events:test",
        title="Count",
        evidence=[],
        text=json.dumps(
            {
                "equipment": "CV-01",
                "count": 3,
                "event_code": None,
                "by_code": {"MOTOR_OVERLOAD": 2, "RUNNING": 1},
                "since": None,
            }
        ),
    )
    summary = event_summary(card)
    assert summary["headline"] == "2 motor overload · 1 running"
    assert "3 matching records" in summary["scope"]
    assert "stop" not in summary["headline"]
    card.text = json.dumps(
        {
            "equipment": "BF-10",
            "count": 0,
            "event_code": "MOTOR_OVERLOAD",
            "by_code": {},
            "since": None,
        }
    )
    assert event_summary(card)["headline"] == "0 motor overload"


def test_context_keeps_user_clarification_but_never_reuses_generated_claims():
    turns = [
        {"message": "The conveyor stopped", "result": {"answer": "UNTRUSTED_PAST_OUTPUT"}},
        {"message": "BF-10", "result": {}},
    ]
    context = conversation_context(turns, "What does the manual say?")
    assert "BF-10" in context and context.endswith("What does the manual say?")
    assert "UNTRUSTED_PAST_OUTPUT" not in context
    with pytest.raises(ValueError, match="Start a new chat"):
        conversation_context([{"message": "x" * 4000}], "A follow-up")


def test_citations_group_exact_excerpts_and_withheld_answers_have_no_sources(tmp_path):
    metadata, bundle = load_scenario(ROOT, "sensor_stop")
    result = answer_question(
        bundle, metadata["question"], metadata["question_at"], metadata["dataset"], tmp_path
    )
    source_groups, numbers = cited_sources(result)
    assert len(source_groups) == 1
    source = next(iter(source_groups.values()))
    assert (
        source["name"] == "events.log" and len(source["refs"]) == 4
    )  # Duplicate exports retained.
    assert all(mark == [1] for mark in numbers.values())
    result.status = "withheld"
    assert cited_sources(result) == ({}, {})


def test_live_style_chat_sources_and_settings_change_without_model_calls(monkeypatch, tmp_path):
    monkeypatch.setenv("FACTORY_RUNTIME", str(tmp_path / "ui"))
    calls = []

    def fake_live(bundle, question, cutoff, dataset, runtime, **kwargs):
        calls.append(question)
        result = answer_question(bundle, question, cutoff, dataset, runtime, mode="offline")
        result.mode, result.search_mode = kwargs["mode"], kwargs["search_mode"]
        result.status = "answered"
        citation = next(c.id for c in result.evidence if c.id.startswith("passage:S3:"))
        result.response = answer(
            fact_ids=[f.id for f in result.facts],
            findings=[
                SupportedClaim(id="test", text="Test released response.", citations=[citation])
            ],
        )
        return result

    monkeypatch.setattr("factory_assistant.answer_ui.answer_question", fake_live)
    app = AppTest.from_file(str(ROOT / "app.py")).run(timeout=15)
    next(s for s in app.selectbox if s.label == "Production line").select("sensor_stop").run(
        timeout=15
    )
    next(r for r in app.radio if r.label == "Assistant").set_value("live").run(timeout=15)
    assert any(b.label == "Troubleshoot a stop" for b in app.button)  # Example questions.
    app.chat_input[0].set_value("carton buffer SENSOR_BLOCKED").run(timeout=15)
    assert not app.exception and len(calls) == 1
    assert any("Test released response. [2]" in m.value for m in app.markdown)
    sources = next(e for e in app.expander if e.label.startswith("📄 Sources"))
    assert "[1] events.log" in sources.label and "[2] manual.txt" in sources.label
    assert not any("passage:S3:" in m.value for m in app.markdown)
    assert not app.success  # No blanket green 'verified' banner.
    app.run(timeout=15)
    assert len(calls) == 1
    next(r for r in app.radio if r.label == "Passage search").set_value("keyword").run(timeout=15)
    assert len(app.chat_message) == 0 and len(calls) == 1  # New settings start a new chat.
